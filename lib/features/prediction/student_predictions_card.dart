final _historyProvider = FutureProvider.autoDispose.family<List<PredictionView>, String>((ref, id) async {
  final user = ref.watch(authStateProvider).valueOrNull;
  if (user == null) return const [];
  return ref.watch(predictionServiceProvider).historyFor(id, user);
});

/// Latest risk signal and SGPA range for a student, the main factors behind
/// each, and earlier predictions. Hidden when there are none.
class StudentPredictionsCard extends ConsumerWidget {
  final String studentId;
  const StudentPredictionsCard({super.key, required this.studentId});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final history = ref.watch(_historyProvider(studentId)).valueOrNull ?? const [];
    if (history.isEmpty) return const SizedBox.shrink();
    final theme = Theme.of(context);

    final risk = history.where((p) => p.record.task == ModelTask.risk.name).firstOrNull;
    final forecast = history.where((p) => p.record.task == ModelTask.forecast.name).firstOrNull;
    final synthetic = (risk?.record.synthetic ?? false) || (forecast?.record.synthetic ?? false);

    return Padding(
      padding: const EdgeInsets.only(bottom: AppSpacing.lg),
      child: AnalyticsCard(
        title: 'Predictions',
        subtitle: 'Decision support only: estimates from past patterns, with the factors that drove them. '
            'They are not shown to students and do not make decisions.',
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            if (synthetic)
              Container(
                margin: const EdgeInsets.only(bottom: AppSpacing.md),
                padding: const EdgeInsets.all(AppSpacing.md),
                decoration: BoxDecoration(
                  color: theme.appColors.danger.withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(AppRadius.control),
                ),
                child: Text(
                  'Generated by a test model trained on synthetic data. Do not use for real decisions.',
                  style: TextStyle(color: theme.appColors.danger, fontWeight: FontWeight.w600),
                ),
              ),
            Wrap(
              spacing: AppSpacing.xl,
              runSpacing: AppSpacing.lg,
              children: [
                if (risk != null) SizedBox(width: 460, child: _riskSection(theme, risk)),
                if (forecast != null) SizedBox(width: 460, child: _forecastSection(theme, forecast)),
              ],
            ),
            if (history.length > (risk == null ? 0 : 1) + (forecast == null ? 0 : 1)) ...[
              const SizedBox(height: AppSpacing.md),
              ExpansionTile(
                tilePadding: EdgeInsets.zero,
                title: Text('Prediction history (${history.length})', style: theme.textTheme.titleSmall),
                children: [for (final p in history) _historyRow(theme, p)],
              ),
            ],
          ],
        ),
      ),
    );
  }

  Widget _riskSection(ThemeData theme, PredictionView p) {
    final r = p.record;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Wrap(
          spacing: AppSpacing.sm,
          crossAxisAlignment: WrapCrossAlignment.center,
          children: [
            Text('Academic risk signal for semester ${r.targetSemester}:', style: theme.textTheme.titleSmall),
            RiskChip(r.band, synthetic: r.synthetic),
          ],
        ),
        const SizedBox(height: AppSpacing.xs),
        Text(
          'Estimated probability of academic difficulty: ${((r.probability ?? 0) * 100).round()}%.'
          '${r.band == 'elevated' ? ' Additional support may be beneficial.' : ''}',
          style: theme.textTheme.bodyMedium,
        ),
        const SizedBox(height: AppSpacing.md),
        _factors(theme, p, raisesLabel: 'raises risk', lowersLabel: 'lowers risk', higherIsWorse: true),
        _meta(theme, r.modelId, r.generatedAt),
      ],
    );
  }

  Widget _forecastSection(ThemeData theme, PredictionView p) {
    final r = p.record;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text('Expected SGPA range for semester ${r.targetSemester}:', style: theme.textTheme.titleSmall),
        const SizedBox(height: AppSpacing.xs),
        Text(
          '${r.lower!.toStringAsFixed(1)} – ${r.upper!.toStringAsFixed(1)}',
          style: theme.textTheme.headlineSmall?.copyWith(fontWeight: FontWeight.bold),
        ),
        Text('Central estimate ${r.value!.toStringAsFixed(2)}.', style: theme.textTheme.bodySmall),
        const SizedBox(height: AppSpacing.md),
        _factors(theme, p, raisesLabel: 'raises estimate', lowersLabel: 'lowers estimate', higherIsWorse: false),
        _meta(theme, r.modelId, r.generatedAt),
      ],
    );
  }

  Widget _factors(
    ThemeData theme,
    PredictionView p, {
    required String raisesLabel,
    required String lowersLabel,
    required bool higherIsWorse,
  }) {
    final top = p.contributions.where((c) => c.contribution.abs() > 1e-6).take(4).toList();
    if (top.isEmpty) return const SizedBox.shrink();
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text('Main factors', style: theme.textTheme.labelLarge),
        const SizedBox(height: AppSpacing.xs),
        for (final c in top)
          Padding(
            padding: const EdgeInsets.only(bottom: 2),
            child: Row(
              children: [
                Icon(
                  c.contribution > 0 ? Icons.arrow_upward_rounded : Icons.arrow_downward_rounded,
                  size: 16,
                  color: (c.contribution > 0) == higherIsWorse ? theme.appColors.danger : theme.appColors.success,
                ),
                const SizedBox(width: AppSpacing.xs),
                Expanded(
                  child: Text(
                    '${FeatureSpec.labels[c.feature] ?? c.feature}: ${_formatValue(c.feature, c.value)} '
                    '(${c.contribution > 0 ? raisesLabel : lowersLabel})',
                    style: theme.textTheme.bodySmall,
                  ),
                ),
              ],
            ),
          ),
        const SizedBox(height: AppSpacing.xs),
        Text('Compared with the average student in the training data.',
            style: theme.textTheme.bodySmall?.copyWith(color: theme.colorScheme.onSurfaceVariant)),
      ],
    );
  }

  Widget _meta(ThemeData theme, String modelId, DateTime at) => Padding(
        padding: const EdgeInsets.only(top: AppSpacing.sm),
        child: Text(
          'Model $modelId · ${DateFormat('d MMM yyyy, h:mm a').format(at)}',
          style: theme.textTheme.bodySmall?.copyWith(color: theme.colorScheme.onSurfaceVariant, fontSize: 11),
        ),
      );

  Widget _historyRow(ThemeData theme, PredictionView p) {
    final r = p.record;
    final what = r.task == ModelTask.risk.name
        ? 'Risk ${RiskChip.label(r.band)} (${((r.probability ?? 0) * 100).round()}%)'
        : 'SGPA ${r.lower!.toStringAsFixed(1)}–${r.upper!.toStringAsFixed(1)}';
    return ListTile(
      dense: true,
      contentPadding: EdgeInsets.zero,
      title: Text('Sem ${r.targetSemester} · $what${r.synthetic ? ' · test model' : ''}'),
      subtitle: Text('${DateFormat('d MMM yyyy, h:mm a').format(r.generatedAt)} · ${r.modelId}'),
    );
  }

  static String _formatValue(String feature, double? v) {
    if (v == null) return 'missing';
    if (feature.contains('attendance') && !feature.contains('slope') ||
        feature.contains('score') ||
        feature.startsWith('school') ||
        feature == 'prev_percentage') {
      return '${v.toStringAsFixed(1)}%';
    }
    if (v == v.roundToDouble()) return v.toInt().toString();
    return v.toStringAsFixed(2);
  }
}
